function glyphMask(font, str, scale, pad) {
    const glyphs = [...str].map(ch => {
        const g = font[ch];
        if (!g) throw new Error(`8-bit font has no glyph for "${ch}"`);
        return g;
    });
    const rows = glyphs[0].length, w = glyphs.reduce((s, g, i) => s + (g[0].length + (i ? 1 : 0)) * scale, 0);
    const m = new Mask(w + pad * 2, rows * scale + pad * 2);
    let cx = pad;
    glyphs.forEach(g => {
        g.forEach((row, j) => [...row].forEach((ch, i) => {
            if (ch !== '#') return;
            for (let sy = 0; sy < scale; sy++) for (let sx = 0; sx < scale; sx++) m.set(cx + i * scale + sx, pad + j * scale + sy);
        }));
        cx += (g[0].length + 1) * scale;
    });
    return { m, w, h: rows * scale, pad };
}

// (x, y) is the top-left of the first letter; shadow drops one pixel down-right
function nesText(p, str, x, y, { color = NES.white, shadow, outline, scale = 1, anchor = 'left', micro = false } = {}) {
    const { m, w, pad } = glyphMask(micro ? MICRO_FONT : NES_FONT, str, scale, 2);
    const ox = (anchor === 'center' ? Math.round(x - w / 2) : anchor === 'right' ? x - w : x) - pad, oy = y - pad;
    if (outline) p.mask(m.grow(true), outline, ox, oy);
    if (shadow) p.mask(m, shadow, ox + 1, oy + 1);
    p.mask(m, color, ox, oy);
    return w;
}

// Title lettering: the big font scaled up, a light top half over a darker
// bottom half, a black outline and a hard drop shadow
function nesLogo(p, str, x, y, { scale = 3, top, bottom, shine = NES.white, shadow = NES.black, drop = 2, anchor = 'left', edge = NES.black } = {}) {
    const { m, w, h, pad } = glyphMask(NES_FONT, str, scale, 3);
    const ox = (anchor === 'center' ? Math.round(x - w / 2) : x) - pad, oy = y - pad;
    const line = m.grow(false);
    p.mask(line, shadow, ox + drop, oy + drop);
    p.mask(line, edge, ox, oy);
    // a one-pixel shine along the top of every stroke
    p.mask(m, (mx, my) => (!m.get(mx, my - 1) ? shine : my - pad < h / 2 ? top : bottom), ox, oy);
    return { w, h };
}

// puffy outlined cloud built from overlapping circles
function nesCloud(p, x, y, s) {
    const puffs = [[0, 6, 6], [8, 2, 8], [17, 5, 7], [-6, 9, 4], [24, 9, 4]]
        .map(([dx, dy, r]) => [x + Math.round(dx * s), y + Math.round(dy * s), Math.max(3, Math.round(r * s))]);
    const base = y + Math.round(12 * s);
    const puff = (grow, c) => puffs.forEach(([cx, cy, r]) => {
        for (let j = -r - grow; j <= r + grow; j++) {
            for (let i = -r - grow; i <= r + grow; i++) {
                if (i * i + j * j <= (r + grow) ** 2 + r * 0.8 && cy + j <= base + grow) p.set(cx + i, cy + j, typeof c === 'function' ? c(cy + j) : c);
            }
        }
    });
    puff(1, NES.black);
    puff(0, py => (py > base - 3 ? NES.ice : NES.white));
}

// Blinking "PUSH START", the one line every title screen shares
function pushStart(p, f, x, y) {
    if (f % 12 < 8) nesText(p, 'PUSH START', x, y, { anchor: 'center', shadow: NES.black });
}
